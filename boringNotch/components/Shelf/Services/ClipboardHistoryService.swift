extension NSPasteboard.PasteboardType {
    /// Marks what Boring Notch puts on the pasteboard, so the history doesn't record it a second time.
    static let boringNotchClipboard = NSPasteboard.PasteboardType("com.theboringteam.boringnotch.clipboard-history")

    /// Markers apps add to secrets and throwaway content (see nspasteboard.org).
    static let privateMarkers: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"),
    ]
}

/// What a pasteboard change turned into. Images still need saving, which happens off the main thread.
enum ClipboardCapture {
    case content(ClipboardContent)
    case imageData(Data)
}

struct ClipboardCaptureOptions {
    var captureImages: Bool
    var captureFiles: Bool
    var ignorePrivateContent: Bool
}

enum ClipboardPasteboard {
    static let maxTextBytes = 1_000_000
    static let maxRTFBytes = 512_000
    static let maxImageBytes = 20_000_000

    /// Files win over text, and text over images, so copying cells from a spreadsheet stays text.
    static func read(_ pasteboard: NSPasteboard, options: ClipboardCaptureOptions) -> ClipboardCapture? {
        let types = pasteboard.types ?? []
        guard !types.isEmpty, !types.contains(.boringNotchClipboard) else { return nil }
        if options.ignorePrivateContent, types.contains(where: { NSPasteboard.PasteboardType.privateMarkers.contains($0) }) {
            return nil
        }

        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return options.captureFiles ? .content(.files(urls)) : nil
        }

        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard string.utf8.count <= maxTextBytes else { return nil }
            if let url = link(from: string) {
                return .content(.link(url))
            }
            var rtf = pasteboard.data(forType: .rtf)
            if let data = rtf, data.count > maxRTFBytes { rtf = nil }
            return .content(.text(string, rtf: rtf))
        }

        if options.captureImages,
           let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
           data.count <= maxImageBytes {
            return .imageData(data)
        }

        return nil
    }

    /// Puts an item back on the pasteboard. Returns the new change count, so it can be skipped,
    /// or nil when the item can't be copied (an image whose file is gone), leaving the pasteboard alone.
    static func write(_ item: ClipboardItem, plainTextOnly: Bool = false) -> Int? {
        var imageData: Data?
        if !plainTextOnly, case .image(let fileName, _) = item.content {
            imageData = try? Data(contentsOf: ClipboardStorageService.shared.imageURL(for: fileName))
            guard imageData != nil else { return nil }
        }

        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        if plainTextOnly, let text = item.plainText {
            pasteboard.setString(text, forType: .string)
        } else {
            switch item.content {
            case .text(let string, let rtf):
                pasteboard.setString(string, forType: .string)
                if let rtf { pasteboard.setData(rtf, forType: .rtf) }
            case .link(let url):
                pasteboard.writeObjects([url as NSURL])
                pasteboard.setString(url.absoluteString, forType: .string)
            case .image:
                if let png = imageData {
                    pasteboard.setData(png, forType: .png)
                    if let tiff = NSImage(data: png)?.tiffRepresentation {
                        pasteboard.setData(tiff, forType: .tiff)
                    }
                }
            case .files(let urls):
                pasteboard.writeObjects(urls.map { $0 as NSURL })
            }
        }

        pasteboard.setData(Data(), forType: .boringNotchClipboard)
        return pasteboard.changeCount
    }

    /// What a card hands over when it's dragged out of the notch.
    static func itemProvider(for item: ClipboardItem) -> NSItemProvider {
        switch item.content {
        case .text(let string, _):
            return NSItemProvider(object: string as NSString)
        case .link(let url):
            return NSItemProvider(object: url as NSURL)
        case .image(let fileName, _):
            let url = ClipboardStorageService.shared.imageURL(for: fileName)
            return NSItemProvider(contentsOf: url) ?? NSItemProvider()
        case .files(let urls):
            // One provider per drag, so a multi-file copy drags its first file
            guard let first = urls.first else { return NSItemProvider() }
            return NSItemProvider(contentsOf: first) ?? NSItemProvider(object: first as NSURL)
        }
    }

    /// A single http(s) URL with nothing around it.
    private static func link(from string: String) -> URL? {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace),
              let url = URL(string: trimmed),
              let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https",
              url.host != nil else { return nil }
        return url
    }
}

final class ClipboardStorageService: @unchecked Sendable {
    static let shared = ClipboardStorageService()

    private let directory: URL
    private let imagesDirectory: URL
    private let itemsURL: URL
    private let queue = DispatchQueue(label: "com.theboringteam.boringnotch.clipboard-storage", qos: .utility)
    private let encoder = JSONEncoder()
    private let decoder = JSONDecoder()

    private init() {
        let fm = FileManager.default
        let support = try? fm.url(for: .applicationSupportDirectory, in: .userDomainMask, appropriateFor: nil, create: true)
        directory = (support ?? fm.temporaryDirectory)
            .appendingPathComponent("boringNotch", isDirectory: true)
            .appendingPathComponent("Clipboard", isDirectory: true)
        imagesDirectory = directory.appendingPathComponent("Images", isDirectory: true)
        itemsURL = directory.appendingPathComponent("items.json")
        try? fm.createDirectory(at: imagesDirectory, withIntermediateDirectories: true)
        encoder.dateEncodingStrategy = .iso8601
        decoder.dateDecodingStrategy = .iso8601
    }

    func imageURL(for fileName: String) -> URL {
        imagesDirectory.appendingPathComponent(fileName)
    }

    func load() -> [ClipboardItem] {
        guard let data = try? Data(contentsOf: itemsURL) else { return [] }
        do {
            return try decoder.decode([ClipboardItem].self, from: data)
        } catch {
            print("⚠️ Failed to load clipboard history: \(error.localizedDescription)")
            return []
        }
    }

    /// Encodes and writes in the background, so a burst of copies doesn't stall the UI.
    /// Waits for the write when the app is quitting.
    func save(_ items: [ClipboardItem], synchronously: Bool = false) {
        let url = itemsURL
        let encoder = encoder
        let write = {
            do {
                let data = try encoder.encode(items)
                try data.write(to: url, options: .atomic)
            } catch {
                print("Failed to save clipboard history: \(error.localizedDescription)")
            }
        }
        if synchronously {
            queue.sync(execute: write)
        } else {
            queue.async(execute: write)
        }
    }

    /// Saves an image as PNG, named by the hash of what was copied so the same image is stored once.
    func storeImage(_ data: Data) -> (fileName: String, pixelSize: CGSize)? {
        let isPNG = data.starts(with: [0x89, 0x50, 0x4E, 0x47])
        guard let rep = NSBitmapImageRep(data: data),
              let png = isPNG ? data : rep.representation(using: .png, properties: [:]) else { return nil }

        let hash = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
        let fileName = String(hash.prefix(32)) + ".png"
        let url = imageURL(for: fileName)
        if FileManager.default.fileExists(atPath: url.path) {
            // Fresh date, so a cleanup that's already queued leaves it alone (see removeImages)
            try? FileManager.default.setAttributes([.modificationDate: Date()], ofItemAtPath: url.path)
        } else {
            do {
                try png.write(to: url, options: .atomic)
            } catch {
                print("Failed to save clipboard image: \(error.localizedDescription)")
                return nil
            }
        }
        return (fileName, CGSize(width: rep.pixelsWide, height: rep.pixelsHigh))
    }

    /// Deletes images no item points to any more. Images saved in the last minute are left alone,
    /// since one may belong to a copy that is still being recorded.
    func removeImages(notIn keep: Set<String>) {
        let dir = imagesDirectory
        queue.async {
            let fm = FileManager.default
            let files = (try? fm.contentsOfDirectory(at: dir, includingPropertiesForKeys: [.contentModificationDateKey])) ?? []
            let cutoff = Date().addingTimeInterval(-60)
            for file in files where !keep.contains(file.lastPathComponent) {
                let modified = (try? file.resourceValues(forKeys: [.contentModificationDateKey]))?.contentModificationDate
                if let modified, modified > cutoff { continue }
                try? fm.removeItem(at: file)
            }
        }
    }

    /// Used when "Keep history after quitting" is turned off.
    func deleteSavedHistory() {
        let url = itemsURL
        queue.async {
            try? FileManager.default.removeItem(at: url)
        }
    }

    /// Images are files even when the history isn't kept, so they go when the app quits.
    func removeAllImages() {
        let dir = imagesDirectory
        queue.sync {
            let files = (try? FileManager.default.contentsOfDirectory(at: dir, includingPropertiesForKeys: nil)) ?? []
            for file in files {
                try? FileManager.default.removeItem(at: file)
            }
        }
    }
}

/// Small, downsampled thumbnails for image cards.
enum ClipboardThumbnailCache {
    // NSCache is thread-safe
    private static let cache = NSCache<NSString, NSImage>()

    static func cached(_ fileName: String) -> NSImage? {
        cache.object(forKey: fileName as NSString)
    }

    static func thumbnail(for fileName: String, maxPixelSize: Int = 360) async -> NSImage? {
        if let image = cached(fileName) { return image }
        let url = ClipboardStorageService.shared.imageURL(for: fileName)
        let image = await Task.detached(priority: .utility) { () -> NSImage? in
            guard let source = CGImageSourceCreateWithURL(url as CFURL, nil) else { return nil }
            let options: [CFString: Any] = [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceCreateThumbnailWithTransform: true,
                kCGImageSourceThumbnailMaxPixelSize: maxPixelSize,
            ]
            guard let cgImage = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
            return NSImage(cgImage: cgImage, size: NSSize(width: cgImage.width, height: cgImage.height))
        }.value
        if let image {
            cache.setObject(image, forKey: fileName as NSString)
        }
        return image
    }
}
